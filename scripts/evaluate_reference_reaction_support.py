@lru_cache(maxsize=500_000)
def _canonicalize_component_cached(smiles: str, isomeric: bool) -> str | None:
    text = str(smiles).strip()
    if not text:
        return None
    mol = Chem.MolFromSmiles(text)
    if mol is None:
        return None
    return Chem.MolToSmiles(
        mol,
        canonical=True,
        isomericSmiles=bool(isomeric),
    )


def canonicalize_component(smiles: str, *, isomeric: bool) -> str | None:
    if smiles is None:
        return None
    return _canonicalize_component_cached(str(smiles), bool(isomeric))


def canonicalize_molecule_set(
    smiles_or_components: str | Sequence[str],
    *,
    isomeric: bool,
) -> tuple[str, ...] | None:
    """
    Canonicalize a molecule set with SynLaD-like set semantics.

    Dot-separated components are split, individually canonicalized, duplicates
    are removed, and the final components are sorted.  This intentionally
    follows the frozenset-style representation used by SynLaD reaction inputs.
    """
    if isinstance(smiles_or_components, str):
        raw_items: Iterable[str] = [smiles_or_components]
    else:
        raw_items = smiles_or_components

    canonical: set[str] = set()
    saw_any = False
    for item in raw_items:
        if item is None:
            return None
        for component in str(item).split("."):
            component = component.strip()
            if not component:
                continue
            saw_any = True
            canon = canonicalize_component(component, isomeric=isomeric)
            if canon is None:
                return None
            canonical.add(canon)

    if not saw_any or not canonical:
        return None
    return tuple(sorted(canonical))


def make_reaction_identity(
    reactants: str | Sequence[str],
    products: str | Sequence[str],
    *,
    isomeric: bool,
) -> ReactionIdentity | None:
    r = canonicalize_molecule_set(reactants, isomeric=isomeric)
    p = canonicalize_molecule_set(products, isomeric=isomeric)
    if r is None or p is None:
        return None
    return ReactionIdentity(r, p)


# -----------------------------------------------------------------------------
# Route token decoding/parsing.
# -----------------------------------------------------------------------------
def decode_route_token_cell(value: Any) -> list[str]:
    if isinstance(value, list):
        return [str(x) for x in value]
    if isinstance(value, tuple):
        return [str(x) for x in value]
    if value is None or (isinstance(value, float) and math.isnan(value)):
        raise RouteParseError("Empty route-token cell.")

    text = str(value).strip()
    if not text:
        raise RouteParseError("Empty route-token string.")

    try:
        obj = json.loads(text)
    except json.JSONDecodeError:
        try:
            obj = ast.literal_eval(text)
        except Exception as exc:
            raise RouteParseError(
                "Route token cell is neither valid JSON nor a Python list literal."
            ) from exc

    if not isinstance(obj, (list, tuple)):
        raise RouteParseError(f"Decoded route tokens are not a list: {type(obj)!r}")
    return [str(x) for x in obj]


def _require_molecule_token(token: str, context: str) -> None:
    if token in SPECIAL_TOKENS:
        raise RouteParseError(
            f"Expected molecule token in {context}, got special token {token!r}."
        )


def parse_forward_reaction_steps(
    route_tokens: Sequence[str],
    *,
    require_eos: bool = True,
) -> list[ReactionStep]:
    tokens = [str(x) for x in route_tokens]
    if not tokens:
        raise RouteParseError("Empty route.")

    steps: list[ReactionStep] = []
    i = 0
    saw_eos = False

    while i < len(tokens):
        token = tokens[i]

        if token == EOS:
            if i != len(tokens) - 1:
                raise RouteParseError("<EOS> must be the final source-level token.")
            saw_eos = True
            i += 1
            break

        if token in PREFIX_TOKENS:
            # Reference source routes may include a prefix.  Consume it rather
            # than rejecting; generated Stage-2 routes are normally prefix-free.
            i += 1
            continue

        if token == BB:
            if i + 1 >= len(tokens):
                raise RouteParseError("<BB> missing molecule argument.")
            _require_molecule_token(tokens[i + 1], "<BB>")
            i += 2
            continue

        if token == REV_RXN:
            raise RouteParseError("<REV_RXN> encountered; Stage 2F-0 expects forward routes.")

        if token == FWD_RXN:
            i += 1
            reactants: list[str] = []
            while i < len(tokens) and tokens[i] != FWD_RXN_RUN:
                _require_molecule_token(tokens[i], "<FWD_RXN> reactants")
                reactants.append(tokens[i])
                i += 1

            if not reactants:
                raise RouteParseError("<FWD_RXN> has no reactants.")
            if i >= len(tokens) or tokens[i] != FWD_RXN_RUN:
                raise RouteParseError("<FWD_RXN> missing first <FWD_RXN_RUN>.")

            i += 1
            if i >= len(tokens):
                raise RouteParseError("<FWD_RXN> missing product molecule.")
            product = tokens[i]
            _require_molecule_token(product, "<FWD_RXN> product")
            i += 1

            if i >= len(tokens) or tokens[i] != FWD_RXN_RUN:
                raise RouteParseError("<FWD_RXN> missing closing <FWD_RXN_RUN>.")

            steps.append(
                ReactionStep(
                    step_idx=len(steps),
                    reactants=tuple(reactants),
                    product=product,
                )
            )
            i += 1
            continue

        raise RouteParseError(f"Unexpected source-level token {token!r} at index {i}.")

    if i != len(tokens):
        raise RouteParseError("Route parser did not consume the complete sequence.")
    if require_eos and not saw_eos:
        raise RouteParseError("Route is missing final <EOS>.")
    return steps


