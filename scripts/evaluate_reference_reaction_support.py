def auto_choose_column(columns: Sequence[str], candidates: Sequence[str], label: str) -> str:
    for col in candidates:
        if col in columns:
            return col
    raise KeyError(
        f"Could not auto-detect {label} column. Available={list(columns)}; "
        f"tried={list(candidates)}"
    )


def iter_route_cells(
    path: str | Path,
    *,
    route_column: str,
) -> tuple[list[Any], str, int]:
    p = Path(path)
    suffix = p.suffix.lower()

    if suffix == ".csv":
        df = pd.read_csv(p)
        col = (
            auto_choose_column(df.columns, AUTO_ROUTE_COLUMNS, "route-token")
            if route_column == "auto"
            else route_column
        )
        if col not in df.columns:
            raise KeyError(f"{p}: no column {col!r}; available={list(df.columns)}")
        return df[col].tolist(), col, len(df)

    if suffix in {".jsonl", ".json"}:
        values: list[Any] = []
        chosen: str | None = None
        with p.open("r", encoding="utf-8") as f:
            if suffix == ".json":
                payload = json.load(f)
                records = payload if isinstance(payload, list) else [payload]
            else:
                records = [json.loads(line) for line in f if line.strip()]

        for obj in records:
            if isinstance(obj, (list, tuple)):
                values.append(obj)
                if chosen is None:
                    chosen = "<record-is-token-list>"
                continue
            if not isinstance(obj, dict):
                raise TypeError(f"{p}: expected dict/list records, got {type(obj)!r}")
            if chosen is None:
                chosen = (
                    auto_choose_column(obj.keys(), AUTO_ROUTE_COLUMNS, "route-token")
                    if route_column == "auto"
                    else route_column
                )
            if chosen not in obj:
                raise KeyError(f"{p}: record missing route field {chosen!r}")
            values.append(obj[chosen])
        return values, chosen or route_column, len(values)

    # Plain text: one route-token JSON/Python-list per line.
    with p.open("r", encoding="utf-8") as f:
        values = [line.strip() for line in f if line.strip()]
    return values, "<line>", len(values)


def iter_reaction_smiles(
    path: str | Path,
    *,
    reaction_column: str,
) -> tuple[list[str], str, int]:
    p = Path(path)
    suffix = p.suffix.lower()

    if suffix == ".csv":
        df = pd.read_csv(p)
        col = (
            auto_choose_column(df.columns, AUTO_REACTION_COLUMNS, "reaction-SMILES")
            if reaction_column == "auto"
            else reaction_column
        )
        if col not in df.columns:
            raise KeyError(f"{p}: no column {col!r}; available={list(df.columns)}")
        vals = [str(x).strip() for x in df[col].tolist() if str(x).strip()]
        return vals, col, len(df)

    if suffix in {".jsonl", ".json"}:
        values: list[str] = []
        chosen: str | None = None
        with p.open("r", encoding="utf-8") as f:
            if suffix == ".json":
                payload = json.load(f)
                records = payload if isinstance(payload, list) else [payload]
            else:
                records = [json.loads(line) for line in f if line.strip()]
        for obj in records:
            if isinstance(obj, str):
                values.append(obj.strip())
                chosen = chosen or "<record-is-string>"
                continue
            if not isinstance(obj, dict):
                raise TypeError(f"{p}: expected dict/string records, got {type(obj)!r}")
            if chosen is None:
                chosen = (
                    auto_choose_column(obj.keys(), AUTO_REACTION_COLUMNS, "reaction-SMILES")
                    if reaction_column == "auto"
                    else reaction_column
                )
            if chosen not in obj:
                raise KeyError(f"{p}: record missing reaction field {chosen!r}")
            values.append(str(obj[chosen]).strip())
        return values, chosen or reaction_column, len(values)

    with p.open("r", encoding="utf-8") as f:
        values = [line.strip() for line in f if line.strip()]
    return values, "<line>", len(values)


def parse_reaction_smiles(text: str) -> tuple[str, str]:
    s = str(text).strip()
    if ">>" not in s:
        raise ValueError(f"Reaction SMILES lacks '>>': {s[:120]!r}")
    reactants, products = s.split(">>", 1)
    if not reactants.strip() or not products.strip():
        raise ValueError(f"Reaction SMILES has empty side: {s[:120]!r}")
    return reactants.strip(), products.strip()


