def load_generated_routes(
    path: str | Path,
    *,
    route_column: str,
    route_id_column: str,
) -> tuple[pd.DataFrame, str, str | None]:
    p = Path(path)
    if p.suffix.lower() != ".csv":
        raise ValueError("Generated routes currently require a CSV input.")
    df = pd.read_csv(p)

    used_route_column = (
        auto_choose_column(df.columns, AUTO_ROUTE_COLUMNS, "generated route-token")
        if route_column == "auto"
        else route_column
    )
    if used_route_column not in df.columns:
        raise KeyError(
            f"Generated CSV has no route column {used_route_column!r}; "
            f"available={list(df.columns)}"
        )

    if route_id_column == "auto":
        used_id = next((c for c in AUTO_ROUTE_ID_COLUMNS if c in df.columns), None)
    else:
        used_id = route_id_column
        if used_id not in df.columns:
            raise KeyError(
                f"Generated CSV has no route ID column {used_id!r}; "
                f"available={list(df.columns)}"
            )
    return df, used_route_column, used_id


def support_flags(
    identity_iso: ReactionIdentity | None,
    identity_relaxed: ReactionIdentity | None,
    index: ReactionIndex | None,
) -> dict[str, Any]:
    if index is None:
        return {
            "exact_iso": None,
            "exact_relaxed": None,
            "reactant_iso": None,
            "product_iso": None,
            "reactant_relaxed": None,
            "product_relaxed": None,
            "num_reference_products_for_reactants_iso": None,
            "num_reference_reactant_sets_for_product_iso": None,
        }

    if identity_iso is None or identity_relaxed is None:
        return {
            "exact_iso": False,
            "exact_relaxed": False,
            "reactant_iso": False,
            "product_iso": False,
            "reactant_relaxed": False,
            "product_relaxed": False,
            "num_reference_products_for_reactants_iso": 0,
            "num_reference_reactant_sets_for_product_iso": 0,
        }

    r_iso, p_iso = identity_iso.key()
    r_rel, p_rel = identity_relaxed.key()
    return {
        "exact_iso": (r_iso, p_iso) in index.exact_iso,
        "exact_relaxed": (r_rel, p_rel) in index.exact_no_stereo,
        "reactant_iso": r_iso in index.reactants_iso,
        "product_iso": p_iso in index.products_iso,
        "reactant_relaxed": r_rel in index.reactants_no_stereo,
        "product_relaxed": p_rel in index.products_no_stereo,
        "num_reference_products_for_reactants_iso": len(
            index.products_by_reactants_iso.get(r_iso, set())
        ),
        "num_reference_reactant_sets_for_product_iso": len(
            index.reactants_by_product_iso.get(p_iso, set())
        ),
    }


def evaluate_generated_routes(
    df: pd.DataFrame,
    *,
    route_column: str,
    route_id_column: str | None,
    reference_index: ReactionIndex | None,
    training_index: ReactionIndex | None,
    require_eos: bool,
) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    step_rows: list[dict[str, Any]] = []
    route_rows: list[dict[str, Any]] = []

    for row_idx, row in df.iterrows():
        route_id = row[route_id_column] if route_id_column else row_idx
        base_route = {
            "route_id": route_id,
            "input_row_index": int(row_idx),
        }

        try:
            tokens = decode_route_token_cell(row[route_column])
            steps = parse_forward_reaction_steps(tokens, require_eos=require_eos)
            parse_valid = True
            parse_error = None
        except Exception as exc:
            steps = []
            parse_valid = False
            parse_error = f"{type(exc).__name__}: {exc}"

        per_route_step_rows: list[dict[str, Any]] = []

        for step in steps:
            identity_iso = make_reaction_identity(
                step.reactants, step.product, isomeric=True
            )
            identity_relaxed = make_reaction_identity(
                step.reactants, step.product, isomeric=False
            )
            evaluable = identity_iso is not None and identity_relaxed is not None

            ref = support_flags(identity_iso, identity_relaxed, reference_index)
            train = support_flags(identity_iso, identity_relaxed, training_index)

            r_iso = None if identity_iso is None else ".".join(identity_iso.reactants)
            p_iso = None if identity_iso is None else ".".join(identity_iso.products)
            r_rel = None if identity_relaxed is None else ".".join(identity_relaxed.reactants)
            p_rel = None if identity_relaxed is None else ".".join(identity_relaxed.products)

            step_row = {
                **base_route,
                "step_idx": int(step.step_idx),
                "reactants_raw": json_compact(list(step.reactants)),
                "generated_product_raw": step.product,
                "reaction_evaluable": bool(evaluable),
                "reactants_canonical_isomeric": r_iso,
                "product_canonical_isomeric": p_iso,
                "reaction_canonical_isomeric": (
                    None if r_iso is None or p_iso is None else f"{r_iso}>>{p_iso}"
                ),
                "reactants_canonical_stereo_relaxed": r_rel,
                "product_canonical_stereo_relaxed": p_rel,
                "reaction_canonical_stereo_relaxed": (
                    None if r_rel is None or p_rel is None else f"{r_rel}>>{p_rel}"
                ),
                "reference_exact_reaction_support": ref["exact_iso"],
                "reference_exact_reaction_support_stereo_relaxed": ref["exact_relaxed"],
                "reference_reactant_set_support": ref["reactant_iso"],
                "reference_product_support": ref["product_iso"],
                "reference_reactant_set_support_stereo_relaxed": ref["reactant_relaxed"],
                "reference_product_support_stereo_relaxed": ref["product_relaxed"],
                "reference_num_products_for_reactants": ref[
                    "num_reference_products_for_reactants_iso"
                ],
                "reference_num_reactant_sets_for_product": ref[
                    "num_reference_reactant_sets_for_product_iso"
                ],
                "train_seen_exact_reaction": train["exact_iso"],
                "train_seen_exact_reaction_stereo_relaxed": train["exact_relaxed"],
                "train_seen_reactant_set": train["reactant_iso"],
                "train_seen_product": train["product_iso"],
                "train_novel_exact_reaction": (
                    None if train["exact_iso"] is None or not evaluable else not train["exact_iso"]
                ),
                "train_novel_exact_reaction_stereo_relaxed": (
                    None
                    if train["exact_relaxed"] is None or not evaluable
                    else not train["exact_relaxed"]
                ),
            }
            step_rows.append(step_row)
            per_route_step_rows.append(step_row)

        n_steps = len(per_route_step_rows)
        evaluable_steps = [r for r in per_route_step_rows if r["reaction_evaluable"]]

        def _route_bool(field: str, *, all_steps: bool) -> bool | None:
            vals = [r[field] for r in evaluable_steps if r[field] is not None]
            if not parse_valid or n_steps == 0 or len(vals) != n_steps:
                return False if (reference_index is not None or training_index is not None) else None
            return all(vals) if all_steps else any(vals)

        def _route_frac(field: str) -> float | None:
            vals = [bool(r[field]) for r in evaluable_steps if r[field] is not None]
            if not vals:
                return None
            return safe_fraction(sum(vals), len(vals))

        train_seen_all = _route_bool("train_seen_exact_reaction", all_steps=True)
        train_seen_any = _route_bool("train_seen_exact_reaction", all_steps=False)
        train_novel_vals = [
            r["train_novel_exact_reaction"]
            for r in evaluable_steps
            if r["train_novel_exact_reaction"] is not None
        ]

        route_rows.append(
            {
                **base_route,
                "route_parse_valid": bool(parse_valid),
                "route_parse_error": parse_error,
                "reaction_step_count": int(n_steps),
                "evaluable_reaction_step_count": int(len(evaluable_steps)),
                "all_steps_reference_exact_supported": _route_bool(
                    "reference_exact_reaction_support", all_steps=True
                ),
                "any_step_reference_exact_supported": _route_bool(
                    "reference_exact_reaction_support", all_steps=False
                ),
                "reference_exact_supported_step_fraction": _route_frac(
                    "reference_exact_reaction_support"
                ),
                "all_steps_reference_exact_supported_stereo_relaxed": _route_bool(
                    "reference_exact_reaction_support_stereo_relaxed", all_steps=True
                ),
                "all_steps_train_seen_exact": train_seen_all,
                "any_step_train_seen_exact": train_seen_any,
                "all_steps_train_novel_exact": (
                    False
                    if not parse_valid or n_steps == 0 or len(train_novel_vals) != n_steps
                    else all(bool(x) for x in train_novel_vals)
                )
                if training_index is not None
                else None,
                "any_step_train_novel_exact": (
                    False
                    if not parse_valid or n_steps == 0 or len(train_novel_vals) != n_steps
                    else any(bool(x) for x in train_novel_vals)
                )
                if training_index is not None
                else None,
                "train_seen_exact_step_fraction": _route_frac("train_seen_exact_reaction"),
                "train_novel_exact_step_fraction": _route_frac("train_novel_exact_reaction"),
            }
        )

    step_df = pd.DataFrame(step_rows)
    route_df = pd.DataFrame(route_rows)

    summary = summarize_results(
        step_df,
        route_df,
        reference_enabled=reference_index is not None,
        training_enabled=training_index is not None,
    )
    return step_df, route_df, summary


# -----------------------------------------------------------------------------
# Aggregation.
# -----------------------------------------------------------------------------
def _bool_metric(df: pd.DataFrame, field: str) -> dict[str, Any]:
    if field not in df.columns:
        return {"count": 0, "numerator": 0, "fraction": None}
    s = df[field].dropna()
    vals = [bool(x) for x in s.tolist()]
    return {
        "count": len(vals),
        "numerator": sum(vals),
        "fraction": safe_fraction(sum(vals), len(vals)),
    }


def summarize_results(
    step_df: pd.DataFrame,
    route_df: pd.DataFrame,
    *,
    reference_enabled: bool,
    training_enabled: bool,
) -> dict[str, Any]:
    n_routes = len(route_df)
    n_steps = len(step_df)
    parse_valid = int(route_df["route_parse_valid"].sum()) if n_routes else 0
    evaluable = int(step_df["reaction_evaluable"].sum()) if n_steps else 0

    step_count_values = route_df["reaction_step_count"].tolist() if n_routes else []
    summary: dict[str, Any] = {
        "evaluation": {
            "stage": "stage2f0_reference_reaction_support_and_novelty",
            "policy": "model_free_canonical_reaction_lookup",
            "interpretation": (
                "Dataset support/novelty only; absence from a reference corpus does not "
                "imply chemical infeasibility."
            ),
        },
        "counts": {
            "generated_routes": n_routes,
            "route_parse_valid": parse_valid,
            "route_parse_valid_fraction": safe_fraction(parse_valid, n_routes),
            "generated_reaction_steps": n_steps,
            "evaluable_reaction_steps": evaluable,
            "evaluable_reaction_step_fraction": safe_fraction(evaluable, n_steps),
            "reaction_steps_per_route_min": min(step_count_values) if step_count_values else None,
            "reaction_steps_per_route_median": (
                statistics.median(step_count_values) if step_count_values else None
            ),
            "reaction_steps_per_route_mean": (
                statistics.mean(step_count_values) if step_count_values else None
            ),
            "reaction_steps_per_route_max": max(step_count_values) if step_count_values else None,
        },
    }

    if reference_enabled:
        summary["reference_support_step_level"] = {
            "exact_reaction_isomeric": _bool_metric(
                step_df, "reference_exact_reaction_support"
            ),
            "exact_reaction_stereo_relaxed": _bool_metric(
                step_df, "reference_exact_reaction_support_stereo_relaxed"
            ),
            "reactant_set_isomeric": _bool_metric(
                step_df, "reference_reactant_set_support"
            ),
            "product_isomeric": _bool_metric(step_df, "reference_product_support"),
        }
        summary["reference_support_route_level"] = {
            "all_steps_exact_isomeric": _bool_metric(
                route_df, "all_steps_reference_exact_supported"
            ),
            "all_steps_exact_stereo_relaxed": _bool_metric(
                route_df, "all_steps_reference_exact_supported_stereo_relaxed"
            ),
            "any_step_exact_isomeric": _bool_metric(
                route_df, "any_step_reference_exact_supported"
            ),
        }

    if training_enabled:
        summary["training_novelty_step_level"] = {
            "seen_exact_isomeric": _bool_metric(step_df, "train_seen_exact_reaction"),
            "novel_exact_isomeric": _bool_metric(step_df, "train_novel_exact_reaction"),
            "seen_exact_stereo_relaxed": _bool_metric(
                step_df, "train_seen_exact_reaction_stereo_relaxed"
            ),
            "novel_exact_stereo_relaxed": _bool_metric(
                step_df, "train_novel_exact_reaction_stereo_relaxed"
            ),
            "seen_reactant_set_isomeric": _bool_metric(step_df, "train_seen_reactant_set"),
            "seen_product_isomeric": _bool_metric(step_df, "train_seen_product"),
        }
        summary["training_novelty_route_level"] = {
            "all_steps_seen_exact": _bool_metric(route_df, "all_steps_train_seen_exact"),
            "any_step_seen_exact": _bool_metric(route_df, "any_step_train_seen_exact"),
            "all_steps_novel_exact": _bool_metric(route_df, "all_steps_train_novel_exact"),
            "any_step_novel_exact": _bool_metric(route_df, "any_step_train_novel_exact"),
        }

        # If both indices are supplied, explicitly stratify reference support by
        # train-seen vs train-novel reactions.  This is often the most useful F-0
        # diagnostic for separating memorized transformations from novel ones.
        if reference_enabled and n_steps:
            strata: dict[str, Any] = {}
            for name, mask_field, mask_value in (
                ("train_seen", "train_seen_exact_reaction", True),
                ("train_novel", "train_novel_exact_reaction", True),
            ):
                if mask_field not in step_df.columns:
                    continue
                mask = step_df[mask_field] == mask_value
                sub = step_df.loc[mask]
                strata[name] = {
                    "reaction_steps": len(sub),
                    "reference_exact_support": _bool_metric(
                        sub, "reference_exact_reaction_support"
                    ),
                    "reference_exact_support_stereo_relaxed": _bool_metric(
                        sub, "reference_exact_reaction_support_stereo_relaxed"
                    ),
                }
            summary["reference_support_stratified_by_training_novelty"] = strata

    return summary


