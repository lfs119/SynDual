class RouteParseError(ValueError):
    pass


@dataclass(frozen=True)
class ReactionStep:
    step_idx: int
    reactants: tuple[str, ...]
    product: str


@dataclass(frozen=True)
class ReactionIdentity:
    """Canonical set-based reaction identity."""

    reactants: tuple[str, ...]
    products: tuple[str, ...]

    def key(self) -> tuple[str, str]:
        return (".".join(self.reactants), ".".join(self.products))

    def reaction_smiles(self) -> str:
        r, p = self.key()
        return f"{r}>>{p}"


