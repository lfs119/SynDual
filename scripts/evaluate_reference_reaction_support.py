class ReactionIndex:
    def __init__(self) -> None:
        # Stereo-sensitive indices.
        self.exact_iso: set[tuple[str, str]] = set()
        self.reactants_iso: set[str] = set()
        self.products_iso: set[str] = set()
        self.products_by_reactants_iso: dict[str, set[str]] = defaultdict(set)
        self.reactants_by_product_iso: dict[str, set[str]] = defaultdict(set)

        # Stereo-relaxed indices.
        self.exact_no_stereo: set[tuple[str, str]] = set()
        self.reactants_no_stereo: set[str] = set()
        self.products_no_stereo: set[str] = set()
        self.products_by_reactants_no_stereo: dict[str, set[str]] = defaultdict(set)
        self.reactants_by_product_no_stereo: dict[str, set[str]] = defaultdict(set)

        self.raw_reaction_records = 0
        self.valid_reaction_records = 0
        self.invalid_reaction_records = 0
        self.duplicate_exact_iso_records = 0

    def add(self, reactants: str | Sequence[str], products: str | Sequence[str]) -> bool:
        self.raw_reaction_records += 1
        iso = make_reaction_identity(reactants, products, isomeric=True)
        relaxed = make_reaction_identity(reactants, products, isomeric=False)
        if iso is None or relaxed is None:
            self.invalid_reaction_records += 1
            return False

        iso_key = iso.key()
        relaxed_key = relaxed.key()
        if iso_key in self.exact_iso:
            self.duplicate_exact_iso_records += 1

        self.exact_iso.add(iso_key)
        self.reactants_iso.add(iso_key[0])
        self.products_iso.add(iso_key[1])
        self.products_by_reactants_iso[iso_key[0]].add(iso_key[1])
        self.reactants_by_product_iso[iso_key[1]].add(iso_key[0])

        self.exact_no_stereo.add(relaxed_key)
        self.reactants_no_stereo.add(relaxed_key[0])
        self.products_no_stereo.add(relaxed_key[1])
        self.products_by_reactants_no_stereo[relaxed_key[0]].add(relaxed_key[1])
        self.reactants_by_product_no_stereo[relaxed_key[1]].add(relaxed_key[0])

        self.valid_reaction_records += 1
        return True

    def metadata(self) -> dict[str, Any]:
        return {
            "raw_reaction_records": self.raw_reaction_records,
            "valid_reaction_records": self.valid_reaction_records,
            "invalid_reaction_records": self.invalid_reaction_records,
            "duplicate_exact_iso_records": self.duplicate_exact_iso_records,
            "unique_exact_reactions_isomeric": len(self.exact_iso),
            "unique_exact_reactions_stereo_relaxed": len(self.exact_no_stereo),
            "unique_reactant_sets_isomeric": len(self.reactants_iso),
            "unique_product_sets_isomeric": len(self.products_iso),
        }


def add_routes_to_index(
    index: ReactionIndex,
    paths: Sequence[str],
    *,
    route_column: str,
    require_eos: bool,
) -> tuple[list[dict[str, Any]], int]:
    provenance: list[dict[str, Any]] = []
    parse_failures = 0

    for path in paths:
        p = Path(path)
        values, used_column, n_records = iter_route_cells(p, route_column=route_column)
        source_steps = 0
        local_failures = 0
        for value in values:
            try:
                tokens = decode_route_token_cell(value)
                steps = parse_forward_reaction_steps(tokens, require_eos=require_eos)
                for step in steps:
                    index.add(step.reactants, step.product)
                    source_steps += 1
            except Exception:
                parse_failures += 1
                local_failures += 1

        provenance.append(
            {
                "path": str(p.resolve()),
                "sha256": sha256_file(p),
                "kind": "route_tokens",
                "used_column": used_column,
                "records": n_records,
                "parsed_steps": source_steps,
                "route_parse_failures": local_failures,
            }
        )

    return provenance, parse_failures


def add_reaction_files_to_index(
    index: ReactionIndex,
    paths: Sequence[str],
    *,
    reaction_column: str,
) -> tuple[list[dict[str, Any]], int]:
    provenance: list[dict[str, Any]] = []
    parse_failures = 0

    for path in paths:
        p = Path(path)
        values, used_column, n_records = iter_reaction_smiles(
            p, reaction_column=reaction_column
        )
        local_failures = 0
        parsed = 0
        for value in values:
            try:
                reactants, products = parse_reaction_smiles(value)
                index.add(reactants, products)
                parsed += 1
            except Exception:
                parse_failures += 1
                local_failures += 1

        provenance.append(
            {
                "path": str(p.resolve()),
                "sha256": sha256_file(p),
                "kind": "reaction_smiles",
                "used_column": used_column,
                "records": n_records,
                "parsed_reactions": parsed,
                "reaction_parse_failures": local_failures,
            }
        )

    return provenance, parse_failures


def build_index(
    *,
    route_files: Sequence[str],
    reaction_files: Sequence[str],
    route_column: str,
    reaction_column: str,
    require_eos: bool,
) -> tuple[ReactionIndex, dict[str, Any]]:
    index = ReactionIndex()
    route_prov, route_failures = add_routes_to_index(
        index,
        route_files,
        route_column=route_column,
        require_eos=require_eos,
    )
    rxn_prov, rxn_failures = add_reaction_files_to_index(
        index,
        reaction_files,
        reaction_column=reaction_column,
    )
    provenance = {
        "sources": [*route_prov, *rxn_prov],
        "route_parse_failures": route_failures,
        "reaction_parse_failures": rxn_failures,
        "index": index.metadata(),
    }
    return index, provenance


