#!/usr/bin/env python3
"""
Stage 2F-0: reference-reaction support and reaction-novelty evaluation.

This script is intentionally model-free and evaluation-only.  It does not use
rxn-lm, AiZynthFinder, or any other reaction predictor.  Instead, it asks two
separate questions for every forward reaction generated by SynDual:

1) Reference support
   Does the canonical reaction (reactant set -> product set) occur in a chosen
   reference reaction corpus / route collection?

2) Training-set novelty
   Was the canonical reaction seen in the synthesis data used to train SynDual?

These are *dataset-support / novelty* diagnostics, not proof of chemical
feasibility.  In particular, a reaction absent from the reference corpus is not
necessarily chemically impossible.

Expected generated-route grammar
--------------------------------
The default input is the Stage 2E-v2 ``route_generation_examples.csv`` with a
``generated_route_tokens`` column containing source-level SynLaD route tokens:

    <BB> BB1
    <BB> BB2
    <FWD_RXN> BB1 BB2 <FWD_RXN_RUN> P1 <FWD_RXN_RUN>
    ...
    <EOS>

Reference/training reactions can be supplied either as route-token files or as
reaction-SMILES files. Multiple files may be provided.

Outputs
-------
* reference_reaction_support_steps.csv
* reference_reaction_support_routes.csv
* reference_reaction_support_summary.json

Recommended interpretation
--------------------------
* reference_exact_reaction_support: exact reaction identity appears in the
  chosen reference corpus.
* train_seen_exact_reaction: exact reaction identity appears in the training
  reaction corpus.
* train_novel_exact_reaction: complement of train_seen_exact_reaction among
  evaluable generated steps.

The script reports both stereo-sensitive and stereo-relaxed identities.
"""

